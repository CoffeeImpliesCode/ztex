class MathFace:
    """The LM Math face, opened once, answering every measurement the
    generated tables need in em of the glyph's font size."""

    def __init__(self, data: bytes) -> None:
        try:
            from fontTools.pens.boundsPen import BoundsPen
            from fontTools.ttLib import TTFont
        except ImportError:
            print('fontTools is required for --math-style-metrics (pip '
                  'install fonttools); the embed path itself does not need it')
            raise SystemExit(1) from None
        self._pen = BoundsPen
        font = TTFont(io.BytesIO(data))
        self.upem = font['head'].unitsPerEm
        self.glyphs = font.getGlyphSet()
        self.cmap = font.getBestCmap()
        self.hmtx = font['hmtx'].metrics
        table = font['MATH'].table
        info = table.MathGlyphInfo
        self.italics: dict[str, float] = {}
        self.top_accents: dict[str, float] = {}
        if info is not None:
            correction = info.MathItalicsCorrectionInfo
            if correction is not None:
                self.italics = dict(zip(correction.Coverage.glyphs,
                                        (r.Value for r in correction.ItalicsCorrection)))
            attachment = info.MathTopAccentAttachment
            if attachment is not None:
                self.top_accents = dict(zip(attachment.TopAccentCoverage.glyphs,
                                            (r.Value for r in attachment.TopAccentAttachment)))
        variants = table.MathVariants
        self.min_connector_overlap = variants.MinConnectorOverlap
        self.ladders = dict(zip(variants.HorizGlyphCoverage.glyphs,
                                variants.HorizGlyphConstruction))
        self.verticals = dict(zip(variants.VertGlyphCoverage.glyphs,
                                  variants.VertGlyphConstruction))
        self.axis_height = table.MathConstants.AxisHeight.Value

    def em(self, value: float) -> float:
        """A font-unit measurement as em, rounded to the tables' precision."""
        return round(value / self.upem, 6)

    def ink(self, name: str) -> tuple[float, float, float, float] | None:
        """The glyph's own outline box as em (x0, y0, x1, y1), or None when
        the glyph paints nothing."""
        pen = self._pen(self.glyphs)
        self.glyphs[name].draw(pen)
        if pen.bounds is None:
            return None
        x0, y0, x1, y1 = pen.bounds
        return self.em(x0), self.em(y0), self.em(x1), self.em(y1)


def zig_ink_fields(ink: tuple[float, float, float, float] | None
                   ) -> list[tuple[str, str]]:
    """The five ink fields of a generated row, in emission order, from an
    outline box: how far the ink rises, how far it hangs below the baseline,
    how far it reaches left of the origin, where it ends on the right of it
    and its lower edge above the baseline. A 0 is left out of the row — the
    Zig default is that same 0, so the row still states the real
    measurement."""
    if ink is None:
        return []
    x0, y0, x1, y1 = ink
    return [(name, num(value)) for name, value in (
        ('asc', max(0.0, y1)),
        ('desc', max(0.0, -y0)),
        ('left', max(0.0, -x0)),
        ('right_edge', max(0.0, x1)),
        ('bottom', max(0.0, y0)),
    ) if value]


def zig_row(
    indent: int,
    fields: list[tuple[str, str]],
    slot: str | None = None,
) -> str:
    """One struct-literal element, formatted the way `zig fmt` would format
    it: inline when it fits inside ZIG_WIDTH, one field per line when it does
    not. `slot` names the field the element fills (`.base = .{ ... }`); None
    for an element of an anonymous list."""
    prefix = ' ' * indent + (f'.{slot} = ' if slot else '') + '.{ '
    inline = prefix + ', '.join(
        f'.{name} = {value}' for name, value in fields) + ' },'
    if len(inline) <= ZIG_WIDTH:
        return inline
    pad = ' ' * (indent + 4)
    body = ',\n'.join(f'{pad}.{name} = {value}' for name, value in fields)
    return f'{prefix.rstrip()}\n{body},\n{" " * indent}}},'


def math_row(face: MathFace, cp: int) -> list[tuple[str, str]] | None:
    """The `Row` fields for `cp`, or None when the face's cmap carries no
    glyph for it: an unmapped codepoint gets no row, so nothing downstream
    inherits an invented advance."""
    name = face.cmap.get(cp)
    if name is None:
        return None
    fields = [('cp', f'0x{cp:04X}'), ('adv', num(face.em(face.hmtx[name][0])))]
    if name in face.italics:
        fields.append(('ic', num(face.em(face.italics[name]))))
    if name in face.top_accents:
        fields.append(('top', num(face.em(face.top_accents[name]))))
    return fields


def series_codepoints(
    runs: tuple[tuple[int, int, int], ...],
    exceptions: dict[int, int],
) -> list[int]:
    """The codepoints one MATH_SERIES entry maps ONTO, ascending: every slot
    of every `(first target, first source, count)` run, with the Letterlike
    slots replacing the run slot their source would have landed on."""
    mapping: dict[int, int] = {}
    for first_target, first_source, count in runs:
        for offset in range(count):
            mapping[first_source + offset] = first_target + offset
    mapping.update(exceptions)
    targets = sorted(mapping.values())
    if len(set(targets)) != len(targets):
        raise SystemExit('a MATH_SERIES maps two codepoints onto one slot')
    return targets


def ladder_entry(face: MathFace, cp: int) -> str | None:
    """One `Ladder` literal: every MATH horizontal size variant of `cp` and,
    where the form declares one, its GlyphAssembly parts in MATH order."""
    name = face.cmap.get(cp)
    construction = face.ladders.get(name) if name is not None else None
    if construction is None:
        return None
    rungs = []
    for variant in construction.MathGlyphVariantRecord:
        glyph = variant.VariantGlyph
        fields = [('req', num(face.em(variant.AdvanceMeasurement))),
                  ('adv', num(face.em(face.hmtx[glyph][0])))]
        fields += zig_ink_fields(face.ink(glyph))
        rungs.append(zig_row(12, fields))
    body = ['        .rungs = &.{', '\n'.join(rungs), '        },']
    assembly = getattr(construction, 'GlyphAssembly', None)
    if assembly is not None:
        parts = []
        for record in assembly.PartRecords:
            glyph = record.glyph
            fields = [('adv', num(face.em(record.FullAdvance)))]
            if record.PartFlags & 0x0001:
                fields.append(('repeat', 'true'))
            fields += [('start_connector', num(face.em(record.StartConnectorLength))),
                       ('end_connector', num(face.em(record.EndConnectorLength)))]
            fields += zig_ink_fields(face.ink(glyph))
            parts.append(zig_row(12, fields))
        body += ['        .parts = &.{', '\n'.join(parts), '        },',
                 '        .min_connector_overlap = '
                 + num(face.em(face.min_connector_overlap)) + ',']
    return '    .{{\n        .cp = 0x{:04X},\n{}\n    }},'.format(cp, '\n'.join(body))



def vertical_ladder_entry(face: MathFace, cp: int) -> str | None:
    """One `VerticalLadder` literal: the base glyph the cmap carries for `cp`,
    the MATH vertical size variants after it, and — where the form declares
    one — its GlyphAssembly parts in MATH order, bottom to top.

    The base record is skipped only when the construction names the base glyph
    as record 0, the same rule `FontFace.variants` applies when it slices the
    ladder: `rungs` therefore indexes exactly like that view, so `rungs[0]` is
    the form one step above the base."""
    name = face.cmap.get(cp)
    construction = face.verticals.get(name) if name is not None else None
    if name is None or construction is None:
        return None
    records = construction.MathGlyphVariantRecord
    # The record naming the base glyph IS the base form; its AdvanceMeasurement
    # is how large a request the base itself covers. A construction naming no
    # such record leaves the base covering nothing and keeps every record.
    base_is_first = bool(records) and records[0].VariantGlyph == name
    base_fields = [('req', num(face.em(
        records[0].AdvanceMeasurement if base_is_first else 0)))]
    base_fields.append(('adv', num(face.em(face.hmtx[name][0]))))
    base_fields += zig_ink_fields(face.ink(name))
    body = [zig_row(8, base_fields, 'base')]

    rungs = []
    for variant in records[1:] if base_is_first else records:
        glyph = variant.VariantGlyph
        fields = [('req', num(face.em(variant.AdvanceMeasurement))),
                  ('adv', num(face.em(face.hmtx[glyph][0])))]
        fields += zig_ink_fields(face.ink(glyph))
        rungs.append(zig_row(12, fields))
    body += ['        .rungs = &.{', '\n'.join(rungs), '        },']

    assembly = getattr(construction, 'GlyphAssembly', None)
    if assembly is not None:
        parts = []
        for record in assembly.PartRecords:
            glyph = record.glyph
            fields = []
            if record.PartFlags & 0x0001:
                fields.append(('repeat', 'true'))
            fields += [('adv', num(face.em(record.FullAdvance))),
                       ('width', num(face.em(face.hmtx[glyph][0]))),
                       ('start', num(face.em(record.StartConnectorLength))),
                       ('end', num(face.em(record.EndConnectorLength)))]
            fields += zig_ink_fields(face.ink(glyph))
            parts.append(zig_row(12, fields))
        body += ['        .parts = &.{', '\n'.join(parts), '        },']
    return '    .{{\n        .cp = 0x{:04X},\n{}\n    }},'.format(cp, '\n'.join(body))


def write_math_style_metrics() -> int:
    root = pathlib.Path(__file__).resolve().parent.parent
    path = root / 'src' / 'fonts' / 'lmmath.zig'
    if not path.is_file():
        print(f'no embedded face: {path}')
        return 1
    face = MathFace(read_embedded(path))

    tables = ''
    for name, label, runs in (
        ('sans', 'sans-serif', MATH_ALPHABETS[0][1]),
        ('mono', 'monospace', MATH_ALPHABETS[1][1]),
    ):
        rows = []
        for first, count in runs:
            for cp in range(first, first + count):
                fields = math_row(face, cp)
                if fields is not None:
                    rows.append(zig_row(4, fields))
        tables += MATH_TABLE.format(name=name, label=label,
                                    count=len(rows), rows='\n'.join(rows))
    primes = [zig_row(4, fields) for fields in
              (math_row(face, cp) for cp in MATH_PRIME_CPS) if fields is not None]
    tables += MATH_TABLE.format(name='primes', label='prime composites',
                                count=len(primes), rows='\n'.join(primes))

    # The blackboard / calligraphic / fraktur slots, all three series in one
    # cp-ascending table: no slot of the three is shared, so `lookup` reads it
    # exactly like `sans` / `mono`.
    slots: set[int] = set()
    for _, runs, exceptions in MATH_SERIES:
        slots.update(series_codepoints(runs, exceptions))
    alphabet = [zig_row(4, fields) for fields in
                (math_row(face, cp) for cp in sorted(slots))
                if fields is not None]
    tables += MATH_ALPHABET_TABLE.format(count=len(alphabet),
                                         rows='\n'.join(alphabet))

    entries = []
    for cp in MATH_STRETCH_CPS:
        entry = ladder_entry(face, cp)
        if entry is None:
            print(f'U+{cp:04X}: no horizontal size construction in LM Math')
            return 1
        entries.append(entry)
    tables += MATH_LADDER_TABLE.format(count=len(entries),
                                       rows='\n'.join(entries))

    vertical = []
    for cp in MATH_VERTICAL_CPS:
        entry = vertical_ladder_entry(face, cp)
        if entry is None:
            print(f'U+{cp:04X}: no vertical size construction in LM Math')
            return 1
        vertical.append(entry)
    tables += MATH_VERTICAL_TABLE.format(count=len(vertical),
                                         rows='\n'.join(vertical))

    out = root / 'src' / 'layout' / 'math_style_metrics.zig'
    out.write_text(MATH_MODULE.format(
        tables=tables,
        min_overlap=num(face.em(face.min_connector_overlap)),
        axis_height=num(face.em(face.axis_height)),
    ).rstrip('\n') + '\n')
    print(f'{out.relative_to(root)}  ({len(MATH_ALPHABETS)} sans/mono, '
          f'{len(alphabet)} bb/cal/frak slots, {len(MATH_PRIME_CPS)} primes, '
          f'{len(entries)} ladders, {len(vertical)} verticals)')
    return 0



