#!/usr/bin/env python3
r"""Embed an OpenType font as a Zig byte array under src/fonts/.

The faces are checked in as source so the renderer is self-contained: no
system font lookup, no network, identical output everywhere. That makes the
generated file part of the build, so it has to be reproducible -- replace the
face on disk and re-run this rather than hand-editing the array.

    scripts/embed_font.py <font.otf> <const_name> [out_basename]

`out_basename` defaults to the const name; pass it when the file name differs
from the symbol, as the existing faces do (`lmroman_regular.zig` holds
`lmroman10_regular_otf`).

The output matches the existing faces byte for byte: one
`pub const <name> = [_]u8{ ... };` per line, with the Z024 lint suppression a
single-line literal needs.

    scripts/embed_font.py --style-metrics

rebuilds src/layout/roman_style_metrics.zig from the bytes ALREADY embedded in
src/fonts/ -- never from a font file on disk, so the metric tables and the
embedded payload cannot drift apart. Needs fontTools: a development-only
dependency. ztex itself links neither Python nor a font library.

    scripts/embed_font.py --ink-metrics

    scripts/embed_font.py --math-style-metrics

rebuilds src/layout/math_style_metrics.zig the same way: the metrics of the
math faces' own MATH data that the bundled tables do not carry — the
sans-serif and monospace alphabets `\mathsf`/`\mathtt` remap ASCII letters
and digits to, the native quadruple prime, the horizontal MATH size ladders
and glyph assemblies of the four horizontally stretchable forms, and the
vertical size ladders and glyph assemblies of every delimiter a fence names.
"""
import io
import pathlib
import re
import sys


def zig_bytes(data: bytes) -> str:
    return ", ".join(f"0x{b:02X}" for b in data)


def main() -> int:
    if len(sys.argv) == 2:
        modes = {
            '--style-metrics': write_style_metrics,
            '--ink-metrics': write_ink_metrics,
            '--math-style-metrics': write_math_style_metrics,
        }
        if sys.argv[1] in modes:
            return modes[sys.argv[1]]()
        print(__doc__)
        return 2
    if len(sys.argv) not in (3, 4):
        print(__doc__)
        return 2
    src = pathlib.Path(sys.argv[1])
    const = sys.argv[2]
    basename = sys.argv[3] if len(sys.argv) == 4 else const
    if not const.isidentifier():
        print(f'not a valid Zig identifier: {const!r}')
        return 2
    if not src.is_file():
        print(f'no such font: {src}')
        return 1
    data = src.read_bytes()
    if not data:
        print(f'{src} is empty')
        return 1
    if data[:4] not in (b'OTTO', b'\x00\x01\x00\x00', b'true', b'ttcf'):
        print(f'{src} does not start with a known sfnt tag: {data[:4]!r}')
        return 1

    root = pathlib.Path(__file__).resolve().parent.parent
    out = root / 'src' / 'fonts' / f'{basename}.zig'
    out.write_text(
        f'//! {src.name} — embedded face, {len(data):,} bytes.\n'
        f'//! Generated by scripts/embed_font.py; do not hand-edit.\n'
        f'pub const {const} = [_]u8{{ {zig_bytes(data)} }}; // ziglint-ignore: Z024\n'
    )
    print(f'{out.relative_to(root)}  ({len(data):,} bytes of font data)')
    return 0


# ── src/layout/roman_style_metrics.zig ─────────────────────────────────────

# The text faces the static metric path measures for \mathrm/\text,
# \textit, \textbf and a nested \textit{\textbf{...}}, in the order the
# generated module declares them — `atom.CharStyle` order, so a switch on the
# style names one table.
STYLE_FACES = (
    ('roman', 'lmroman_regular.zig'),
    ('italic', 'lmroman_italic.zig'),
    ('bold', 'lmroman_bold.zig'),
    ('bold_italic', 'lmroman_bold_italic.zig'),
)

# Codepoint span the text renderer needs: ASCII, Latin-1 Supplement and Latin
# Extended-A/B, so accented letters and dotless i/j are real rows instead of
# estimates. Codepoints the face's cmap does not carry are dropped.
STYLE_CP_RANGE = (0x0020, 0x0250)

STYLE_MODULE = '''//! LM Roman 10 text-style glyph metrics, in points at the 10pt base
//! (em units x 10), generated by scripts/embed_font.py --style-metrics from
//! the bytes embedded in src/fonts/lmroman_regular.zig,
//! src/fonts/lmroman_italic.zig, src/fonts/lmroman_bold.zig and
//! src/fonts/lmroman_bold_italic.zig (Latin Modern 2.005). Do not hand-edit;
//! re-run the generator.
//!
//! `w` is the face's own hmtx advance, `h`/`d` the glyph's REAL ink bounds
//! above/below the baseline (its outline bbox, so a text box bounds the ink
//! that is actually drawn), and `ic` is 0: these are text faces carrying no
//! MATH table, so the font records no italic correction for them. Rows are
//! sorted by `cp` ascending — the binary-search invariant `lookup` relies on.

/// One text-style glyph row: codepoint, advance width, ink height, ink depth
/// and italic correction, all in points at the 10pt base.
pub const Entry = struct {{
    cp: u21,
    w: f32,
    h: f32,
    d: f32,
    ic: f32,
}};

/// The row for `cp` in `table`, or null when it has none: binary search over
/// the `cp`-ascending rows, and the only reader of the tables below.
pub fn lookup(table: []const Entry, cp: u21) ?Entry {{
    var lo: usize = 0;
    var hi: usize = table.len;
    while (lo < hi) {{
        const mid = lo + (hi - lo) / 2;
        if (table[mid].cp < cp) lo = mid + 1 else hi = mid;
    }}
    if (lo >= table.len or table[lo].cp != cp) return null;
    return table[lo];
}}

{tables}'''

STYLE_TABLE = '''/// Latin Modern Roman 10 {label}, {count} rows.
pub const {name}: []const Entry = &.{{{rows}
}};

'''


# A generated module declares the face as `pub const NAME = <initializer>;`,
# where the initializer is one `[...]u8{ ... }` literal, or — for a payload too
# big for one source file — a `++` chain of the parts it imports just above the
# declaration (`pub const face = p0.bytes ++ p1.bytes;`). Only such an
# initializer holds font data: a hex literal in a comment or a doc example is
# not part of the face.
EMBED_DECL = re.compile(r'pub const (?P<name>\w+) = (?P<expr>[^;]*);')
EMBED_BYTE = re.compile(r'\b0x[0-9A-Fa-f]{2}\b')
# The byte count the embedder records in the module header.
EMBED_COUNT = re.compile(r'(?P<count>[0-9][0-9,]*) bytes')
# The imports a split face module resolves its parts through.
IMPORT = re.compile(r'const (?P<name>\w+) = @import\("(?P<path>[^"]+)"\);')
PART_REF = re.compile(r'\b(?P<name>\w+)\.bytes\b')


def read_embedded(path: pathlib.Path) -> bytes:
    """The bytes one generated font module's declaration holds.

    Reads the byte-array literal of that ONE declaration and nothing else,
    so a `0xNN` token in a comment or a doc example can never be mistaken
    for font data, and checks the payload against the byte count in the
    module header, so a truncated or hand-edited initializer fails here
    instead of feeding fontTools something other than the embedded face.
    A split face (`pub const face = p0.bytes ++ p1.bytes;`) is followed
    through the parts it imports, each part read by this same rule.
    """
    text = path.read_text()
    decls = list(EMBED_DECL.finditer(text))
    faces = [m for m in decls
             if '[_]u8{' in m['expr'] or PART_REF.search(m['expr'])]
    if not faces:
        print(f'{path}: no embedded byte array to read')
        raise SystemExit(1)
    if len(faces) > 1:
        print(f'{path}: {len(faces)} embedded byte arrays, expected one face')
        raise SystemExit(1)
    face = faces[0]
    if '[_]u8{' in face['expr']:
        data = bytes(int(tok, 16) for tok in EMBED_BYTE.findall(face['expr']))
    else:
        parts = {m['name']: path.parent / m['path']
                 for m in IMPORT.finditer(text)}
        chunks = []
        for ref in PART_REF.finditer(face['expr']):
            name = ref['name']
            if name not in parts:
                print(f'{path}: face references {name}, which it does not import')
                raise SystemExit(1)
            chunks.append(read_embedded(parts[name]))
        data = b''.join(chunks)
    header = EMBED_COUNT.search(text[:face.start()])
    if header is not None:
        declared = int(header['count'].replace(',', ''))
        if len(data) != declared:
            print(f'{path}: initializer holds {len(data):,} bytes, '
                  f'header declares {declared:,}')
            raise SystemExit(1)
    return data


def at_base(value: float, upem: int) -> float:
    """A font-unit measurement in points at the 10pt base (em x 10)."""
    return value * 10.0 / upem


def num(value: float) -> str:
    """A measurement as Zig source: six decimals, trailing zeros dropped."""
    text = f'{value:.6f}'.rstrip('0').rstrip('.')
    return '0' if text in ('', '-0') else text


def style_rows(data: bytes) -> list[tuple[int, float, float, float]]:
    """`(cp, w, h, d)` rows for one embedded face, ascending by `cp`.

    `w` is the hmtx advance; `h`/`d` are the glyph's own ink bounds, so a
    blank glyph (space) contributes no ink at all. fontTools is imported
    here, keeping the plain `embed_font.py <font.otf>` path dependency-free.
    """
    try:
        from fontTools.pens.boundsPen import BoundsPen
        from fontTools.ttLib import TTFont
    except ImportError:
        print('fontTools is required for --style-metrics (pip install '
              'fonttools); the embed path itself does not need it')
        raise SystemExit(1) from None

    font = TTFont(io.BytesIO(data))
    upem = font['head'].unitsPerEm
    advances = font['hmtx'].metrics
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    rows = []
    for cp in range(*STYLE_CP_RANGE):
        name = cmap.get(cp)
        if name is None:
            continue
        pen = BoundsPen(glyphs)
        glyphs[name].draw(pen)
        bounds = pen.bounds or (0.0, 0.0, 0.0, 0.0)
        rows.append((
            cp,
            at_base(advances[name][0], upem),
            at_base(max(0.0, bounds[3]), upem),
            at_base(max(0.0, -bounds[1]), upem),
        ))
    return rows


def write_style_metrics() -> int:
    root = pathlib.Path(__file__).resolve().parent.parent
    tables = ''
    for name, source in STYLE_FACES:
        path = root / 'src' / 'fonts' / source
        if not path.is_file():
            print(f'no embedded face: {path}')
            return 1
        rows = style_rows(read_embedded(path))
        body = ''.join(
            f'\n    .{{ .cp = 0x{cp:04X}, .w = {num(w)}, .h = {num(h)}, '
            f'.d = {num(d)}, .ic = 0 }}, // U+{cp:04X}'
            for cp, w, h, d in rows
        )
        tables += STYLE_TABLE.format(
            name=name,
            label=source[len('lmroman_'):-len('.zig')].replace('_', ' '),
            count=len(rows),
            rows=body,
        )
    out = root / 'src' / 'layout' / 'roman_style_metrics.zig'
    # The last table leaves a blank line behind; `zig fmt` drops it, so the
    # generated file is written the way the formatter leaves it.
    out.write_text(STYLE_MODULE.format(tables=tables).rstrip('\n') + '\n')
    print(f'{out.relative_to(root)}  ({len(STYLE_FACES)} tables)')
    return 0


