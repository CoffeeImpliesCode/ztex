# The alphabets `\mathsf` / `\mathtt` remap ASCII letters and digits to, as
# `(first codepoint, count)` runs: capitals, lowercase and digits of the math
# sans-serif and monospace series. Layout owns the mapping; this generator
# owns the measurement of what the mapping lands on.
MATH_ALPHABETS = (
    ('sans', ((0x1D5A0, 26), (0x1D5BA, 26), (0x1D7E2, 10))),
    ('mono', ((0x1D670, 26), (0x1D68A, 26), (0x1D7F6, 10))),
)

# The codepoints the BLACKBOARD / CALLIGRAPHIC / FRAKTUR mappings land on, in
# the shape layout owns them (`mathBb` / `mathCal` / `mathFrak`): runs of
# `(first target, first source, count)` — capitals, lowercase, digits — plus
# the reserved Letterlike slots each run skips for a source codepoint. Layout
# keeps the mapping; this generator owns the measurement of what it lands on,
# so `\mathbb{H}` is measured by the U+210D glyph the face actually draws and
# not by an ASCII estimate.
MATH_SERIES = (
    ('blackboard', ((0x1D538, 0x41, 26), (0x1D552, 0x61, 26),
                    (0x1D7D8, 0x30, 10)),
     {0x43: 0x2102, 0x48: 0x210D, 0x4E: 0x2115, 0x50: 0x2119, 0x51: 0x211A,
      0x52: 0x211D, 0x5A: 0x2124}),
    ('calligraphic', ((0x1D49C, 0x41, 26), (0x1D4B6, 0x61, 26)),
     {0x42: 0x212C, 0x45: 0x2130, 0x46: 0x2131, 0x48: 0x210B, 0x49: 0x2110,
      0x4C: 0x2112, 0x4D: 0x2133, 0x52: 0x211B, 0x65: 0x212F, 0x67: 0x210A,
      0x6F: 0x2134}),
    ('fraktur', ((0x1D504, 0x41, 26), (0x1D51E, 0x61, 26)),
     {0x43: 0x212D, 0x48: 0x210C, 0x49: 0x2111, 0x52: 0x211C, 0x5A: 0x2128}),
)

# The native prime composites the hand-measured tables do not carry: U+2032
# and U+2033 have rows there, the TRIPLE and the QUADRUPLE had none, so a run
# of three or four primes fell to the 0.5em estimate while the face draws
# them as one composite glyph of its own (0.711em and 0.911em).
MATH_PRIME_CPS = (0x2034, 0x2057)

# The codepoints a HORIZONTAL stretch request names: the two combining
# accents that grow over their argument (`\widehat`, `\widetilde`) and the
# two curly bracket halves an over/under brace is built from. Each is the
# base glyph of its own MATH HorizontalGlyphConstruction; layout names the
# codepoint, never a glyph id.
MATH_STRETCH_CPS = (0x0302, 0x0303, 0x23DE, 0x23DF)

# Vertical stretch requests name the fence delimiters and the radical.
# Keep this list sorted so the generated ladders are cp-sorted.
MATH_VERTICAL_CPS = (
    0x0028, 0x0029, 0x002F, 0x005B, 0x005D, 0x007B, 0x007C, 0x007D,
    0x2016, 0x221A, 0x2223, 0x2308, 0x2309, 0x230A, 0x230B, 0x27E8, 0x27E9,
)

# Maximum width of a generated Zig line, matching `zig fmt`'s own limit: an
# element that fits stays on one line and one that does not breaks a field per
# line, which is what the formatter does — so the generated file needs no
# reformatting.
ZIG_WIDTH = 100

MATH_MODULE = r'''//! LM Math measurements the bundled tables do not carry, in em of the
//! glyph's own font size, generated by scripts/embed_font.py
//! --math-style-metrics from the bytes embedded in src/fonts/lmmath.zig — the
//! face font.zig loads and draws, so a generated row can never describe a
//! glyph of another face. Do not hand-edit; re-run the generator.
//!
//! Five groups:
//!
//!   * `sans` / `mono`: the math alphabets. Layout remaps a `\mathsf` letter
//!     or digit to U+1D5A0.. and a `\mathtt` one to U+1D670.. and then asks
//!     the metric source about the MAPPED codepoint, so the run is measured
//!     by the glyph it actually draws. `adv` is that glyph's own hmtx
//!     advance (every monospace row is 0.525em — the fixed pitch the style
//!     promises), `ic` its MATH ItalicCorrection and `top` its MATH
//!     TopAccentAttachment. Their ink is not repeated here: `ink_metrics.math`
//!     already carries every one of these glyphs, measured from the same
//!     bytes, and two tables claiming one outline can only drift apart.
//!   * `alphabets`: the BLACKBOARD / CALLIGRAPHIC / FRAKTUR slots the math
//!     alphabet mapping lands on, the same `Row` shape and the same hmtx /
//!     ItalicCorrection and TopAccentAttachment measurements `sans` / `mono`
//!     carry. `\mathbb` / `\mathcal` / `\mathfrak` remap a letter to
//!     U+1D538.., U+1D49C.. and U+1D504.. (or, for the handful of letters
//!     Unicode reserves, to the Letterlike slot: ℋ U+210B, 𝔞 U+1D51E); the
//!     rows are the MAPPED codepoint's, so the run is measured by the glyph
//!     it actually draws. Their ink is not repeated here, for the reason
//!     above: `ink_metrics.math` already carries every one of these glyphs.
//!   * `primes`: the native TRIPLE and QUADRUPLE primes the hand-measured
//!     tables lack.
//!   * `ladders`: the HORIZONTAL MATH size variants and glyph assemblies of
//!     the four forms a horizontal request names. A `Rung` is one variant —
//!     `req` the MATH AdvanceMeasurement it covers, `adv` the variant glyph's
//!     own advance, the rest its real outline box. A `Part` is one assembly
//!     record in MATH order, repeated while the item is still too short when
//!     `repeat` is set.
//!   * `verticals`: the VERTICAL size variants and glyph assemblies of every
//!     fence or radical a vertical request names. `base` is the cmap glyph;
//!     `rungs` are the MATH size variants after it, the same ones
//!     the face's own ladder reads — the base is record 0 of every one of
//!     these constructions, so `rungs[0]` is .v1 — and `parts` are the
//!     assembly records bottom to top. A `VerticalPart` turns the MATH axes:
//!     `adv` is its FullAdvance along y, `width` its own hmtx advance along
//!     x, the ink fields its real outline box.
//!
//! Nothing here is estimated: a codepoint the face's cmap does not map gets
//! no row at all, so the consumer keeps its own fallback instead of
//! inheriting an invented advance.

/// One generated row: a codepoint the face draws, its own hmtx advance in em,
/// and the MATH values the face records for it. A null `ic` / `top` is the
/// face recording none — not a zero correction and not a zero attachment.
pub const Row = struct {{
    cp: u21,
    /// the glyph's own hmtx advance, em
    adv: f32,
    /// the MATH ItalicCorrection, em
    ic: ?f32 = null,
    /// the MATH TopAccentAttachment, em right of the glyph origin
    top: ?f32 = null,
}};

/// The row for `cp` in `table`, or null when it has none: binary search over
/// the `cp`-ascending rows, and the only reader of the tables below.
pub fn lookup(table: []const Row, cp: u21) ?Row {{
    var lo: usize = 0;
    var hi: usize = table.len;
    while (lo < hi) {{
        const mid = lo + (hi - lo) / 2;
        if (table[mid].cp < cp) lo = mid + 1 else hi = mid;
    }}
    if (lo >= table.len or table[lo].cp != cp) return null;
    return table[lo];
}}

/// One horizontal MATH size variant of a stretchable form, in em. The ink
/// fields carry the variant glyph's own outline box: `asc` / `desc` above and
/// below the baseline, `left` how far the ink reaches left of the origin,
/// `right_edge` where it ends on the right of it, and `bottom` its lower edge
/// measured up from the baseline (positive for a variant that floats above
/// it, which is every rung of an accent and of a brace half).
pub const Rung = struct {{
    /// the MATH AdvanceMeasurement: the request this variant covers
    req: f32,
    /// the variant glyph's own hmtx advance — the extent it reserves, which
    /// is 0 for a base combining accent: LM Math draws that mark with its
    /// ink left of a zero-width origin
    adv: f32,
    asc: f32 = 0,
    desc: f32 = 0,
    left: f32 = 0,
    right_edge: f32 = 0,
    bottom: f32 = 0,
}};

/// One PartRecord of a horizontal GlyphAssembly, in MATH order.
pub const Part = struct {{
    /// the part's FullAdvance, em: what it advances the next part by
    adv: f32,
    /// the part repeats while the item is still too short (fRepeat)
    repeat: bool = false,
    /// StartConnectorLength, em: ink at this part's left edge the previous
    /// part may overlap
    start_connector: f32 = 0,
    /// EndConnectorLength, em: ink at this part's right edge the next part
    /// may overlap
    end_connector: f32 = 0,
    asc: f32 = 0,
    desc: f32 = 0,
    left: f32 = 0,
    right_edge: f32 = 0,
    bottom: f32 = 0,
}};

/// The horizontal size ladder and assembly of one stretchable codepoint.
pub const Ladder = struct {{
    cp: u21,
    /// the MATH size variants, base glyph first, `req` ascending
    rungs: []const Rung,
    /// the GlyphAssembly parts in MATH order; empty when the form declares no
    /// assembly, so a request past the last rung has nothing to build from
    parts: []const Part = &.{{}},
    /// MathVariants.MinConnectorOverlap, em: the overlap any join keeps even
    /// when both parts offer more
    min_connector_overlap: f32 = 0,
}};

/// The horizontal ladder of `cp`, or null when this face declares none: the
/// form has no size variants and nothing to assemble, so a request for it has
/// no native answer.
pub fn ladder(cp: u21) ?Ladder {{
    for (ladders) |entry| {{
        if (entry.cp == cp) return entry;
    }}
    return null;
}}

/// MathVariants.MinConnectorOverlap, em: the overlap a join of a vertical
/// assembly keeps even when both parts offer more. One value for the face, so
/// it is stated once here — the horizontal `Ladder` entries carry their own
/// copy because they were generated first, and the two are the same
/// measurement of the same field.
pub const min_connector_overlap: f32 = {min_overlap};

/// MathConstants.AxisHeight, em: the math axis of this face. Every vertical
/// form below is axis-centred, so a box placed with the shift
/// (asc−desc)/2 − axis_height sits on it the way the reference engines place
/// one.
pub const axis_height: f32 = {axis_height};

/// One PartRecord of a VERTICAL GlyphAssembly, in MATH order, bottom to top.
/// The record carries no glyph id: it is the `i`th part the face's own
/// vertical assembly reports for the base glyph, so a consumer walks the two
/// in step and never names a glyph.
///
/// `adv` (FullAdvance) and `start` / `end` (StartConnectorLength and
/// EndConnectorLength) run along y — up the stack — and `width` is the part
/// glyph's own hmtx advance along x: how wide the stack is, which the
/// FullAdvance says nothing about. The ink fields are the part glyph's real
/// outline box: `asc` / `desc` above and below the part's own y origin,
/// `left` how far it reaches left of the part's own x origin, `right_edge`
/// where it ends on the right of it, and `bottom` its lower edge above that
/// origin. LM Math draws every assembly piece of these constructions from its
/// own baseline up, so `desc` and `bottom` are 0 for every part: the part's own
/// y origin IS its lower ink edge, and where that origin sits against the
/// fence's baseline is the geometry the consumer computes.
pub const VerticalPart = struct {{
    /// the part repeats while the item is still too short (fRepeat); a
    /// repeat count of 0 drops the record from the walk entirely
    repeat: bool = false,
    /// the part's FullAdvance along y, em: what it advances the next part by
    adv: f32,
    /// the part glyph's own hmtx advance along x, em: how wide the stack is
    width: f32,
    /// StartConnectorLength along y, em: ink at this part's lower edge the
    /// part below it may overlap
    start: f32 = 0,
    /// EndConnectorLength along y, em: ink at this part's upper edge the part
    /// above it may overlap
    end: f32 = 0,
    asc: f32 = 0,
    desc: f32 = 0,
    left: f32 = 0,
    right_edge: f32 = 0,
    bottom: f32 = 0,
}};

/// The vertical size ladder and glyph assembly of one stretchable delimiter,
/// in em. `base` and the `rungs` are `Rung`s like the horizontal ladder's: the
/// base glyph's own hmtx advance and outline box under the AdvanceMeasurement
/// of the record that names it, the variants the same under their own.
pub const VerticalLadder = struct {{
    cp: u21,
    /// the BASE glyph the cmap carries for `cp`, with `req` the
    /// AdvanceMeasurement of the MATH record naming it — the request the base
    /// form covers before any variant does
    base: Rung,
    /// the MATH size variants AFTER the base, `req` ascending; `rungs[0]` is
    /// the form a request one step above the base resolves to
    rungs: []const Rung,
    /// the GlyphAssembly parts in MATH order, bottom to top, index-aligned
    /// with the face's own vertical assembly for the base glyph; empty when
    /// the form declares no assembly, so a request past the last rung has
    /// nothing to build from
    parts: []const VerticalPart = &.{{}},
}};

{tables}'''

