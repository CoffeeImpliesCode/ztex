#!/usr/bin/env python3
"""Embed an OpenType font as a Zig byte array under src/fonts/.

The faces are checked in as source so the renderer is self-contained: no
system font lookup, no network, identical output everywhere. That makes the
generated file part of the build, so it has to be reproducible -- replace the
face on disk and re-run this rather than hand-editing the array.

    scripts/embed_font.py <font.otf> <const_name> [out_basename]

`out_basename` defaults to the const name; pass it when the file name differs
from the symbol, as the existing faces do (`lmroman_regular.zig` holds
`lmroman10_regular_otf`).

The output matches the existing faces byte for byte: one
`pub const <name> = [_]u8{ ... };` per line, with the Z024 lint suppression a
single-line literal needs.

    scripts/embed_font.py --style-metrics

rebuilds src/layout/roman_style_metrics.zig from the bytes ALREADY embedded in
src/fonts/ -- never from a font file on disk, so the metric tables and the
embedded payload cannot drift apart. Needs fontTools: a development-only
dependency. ztex itself links neither Python nor a font library.

    scripts/embed_font.py --ink-metrics

rebuilds src/layout/ink_metrics.zig the same way: the real ink of all five
embedded faces — every glyph's vertical extents (ascent above and descent
below the baseline) plus its horizontal extents (how far the ink reaches
LEFT of the origin and where it ENDS on the right) and the ink's lower edge —
so a glyph is framed by the outline it is drawn from, in the face it is drawn
from.
"""
import io
import pathlib
import re
import sys


def zig_bytes(data: bytes) -> str:
    return ", ".join(f"0x{b:02X}" for b in data)


def main() -> int:
    if len(sys.argv) == 2 and sys.argv[1] == '--style-metrics':
        return write_style_metrics()
    if len(sys.argv) == 2 and sys.argv[1] == '--ink-metrics':
        return write_ink_metrics()
    if len(sys.argv) not in (3, 4):
        print(__doc__)
        return 2
    src = pathlib.Path(sys.argv[1])
    const = sys.argv[2]
    basename = sys.argv[3] if len(sys.argv) == 4 else const
    if not const.isidentifier():
        print(f'not a valid Zig identifier: {const!r}')
        return 2
    if not src.is_file():
        print(f'no such font: {src}')
        return 1
    data = src.read_bytes()
    if not data:
        print(f'{src} is empty')
        return 1
    if data[:4] not in (b'OTTO', b'\x00\x01\x00\x00', b'true', b'ttcf'):
        print(f'{src} does not start with a known sfnt tag: {data[:4]!r}')
        return 1

    root = pathlib.Path(__file__).resolve().parent.parent
    out = root / 'src' / 'fonts' / f'{basename}.zig'
    out.write_text(
        f'//! {src.name} — embedded face, {len(data):,} bytes.\n'
        f'//! Generated by scripts/embed_font.py; do not hand-edit.\n'
        f'pub const {const} = [_]u8{{ {zig_bytes(data)} }}; // ziglint-ignore: Z024\n'
    )
    print(f'{out.relative_to(root)}  ({len(data):,} bytes of font data)')
    return 0


# ── src/layout/roman_style_metrics.zig ─────────────────────────────────────

# The text faces the static metric path measures for \textit, \textbf and a
# nested \textit{\textbf{...}}, in the order the generated module declares
# them.
STYLE_FACES = (
    ('italic', 'lmroman_italic.zig'),
    ('bold', 'lmroman_bold.zig'),
    ('bold_italic', 'lmroman_bold_italic.zig'),
)

# Codepoint span the text renderer needs: ASCII, Latin-1 Supplement and Latin
# Extended-A/B, so accented letters and dotless i/j are real rows instead of
# estimates. Codepoints the face's cmap does not carry are dropped.
STYLE_CP_RANGE = (0x0020, 0x0250)

STYLE_MODULE = '''//! LM Roman 10 text-style glyph metrics, in points at the 10pt base
//! (em units x 10), generated by scripts/embed_font.py --style-metrics from
//! the bytes embedded in src/fonts/lmroman_italic.zig,
//! src/fonts/lmroman_bold.zig and src/fonts/lmroman_bold_italic.zig
//! (Latin Modern 2.005). Do not hand-edit; re-run the generator.
//!
//! `w` is the face's own hmtx advance, `h`/`d` the glyph's REAL ink bounds
//! above/below the baseline (its outline bbox, so a text box bounds the ink
//! that is actually drawn), and `ic` is 0: these are text faces carrying no
//! MATH table, so the font records no italic correction for them. Rows are
//! sorted by `cp` ascending — the binary-search invariant `lookup` relies on.

/// One text-style glyph row: codepoint, advance width, ink height, ink depth
/// and italic correction, all in points at the 10pt base.
pub const Entry = struct {{
    cp: u21,
    w: f32,
    h: f32,
    d: f32,
    ic: f32,
}};

/// The row for `cp` in `table`, or null when it has none: binary search over
/// the `cp`-ascending rows, and the only reader of the tables below.
pub fn lookup(table: []const Entry, cp: u21) ?Entry {{
    var lo: usize = 0;
    var hi: usize = table.len;
    while (lo < hi) {{
        const mid = lo + (hi - lo) / 2;
        if (table[mid].cp < cp) lo = mid + 1 else hi = mid;
    }}
    if (lo >= table.len or table[lo].cp != cp) return null;
    return table[lo];
}}

{tables}'''

STYLE_TABLE = '''/// Latin Modern Roman 10 {label}, {count} rows.
pub const {name}: []const Entry = &.{{{rows}
}};

'''


# A generated module declares the face as `pub const NAME = <initializer>;`,
# where the initializer is one `[...]u8{ ... }` literal, or — for a payload too
# big for one source file — a `++` chain of the parts it imports just above the
# declaration (`pub const face = p0.bytes ++ p1.bytes;`). Only such an
# initializer holds font data: a hex literal in a comment or a doc example is
# not part of the face.
EMBED_DECL = re.compile(r'pub const (?P<name>\w+) = (?P<expr>[^;]*);')
EMBED_BYTE = re.compile(r'\b0x[0-9A-Fa-f]{2}\b')
# The byte count the embedder records in the module header.
EMBED_COUNT = re.compile(r'(?P<count>[0-9][0-9,]*) bytes')
# The imports a split face module resolves its parts through.
IMPORT = re.compile(r'const (?P<name>\w+) = @import\("(?P<path>[^"]+)"\);')
PART_REF = re.compile(r'\b(?P<name>\w+)\.bytes\b')


def read_embedded(path: pathlib.Path) -> bytes:
    """The bytes one generated font module's declaration holds.

    Reads the byte-array literal of that ONE declaration and nothing else,
    so a `0xNN` token in a comment or a doc example can never be mistaken
    for font data, and checks the payload against the byte count in the
    module header, so a truncated or hand-edited initializer fails here
    instead of feeding fontTools something other than the embedded face.
    A split face (`pub const face = p0.bytes ++ p1.bytes;`) is followed
    through the parts it imports, each part read by this same rule.
    """
    text = path.read_text()
    decls = list(EMBED_DECL.finditer(text))
    faces = [m for m in decls
             if '[_]u8{' in m['expr'] or PART_REF.search(m['expr'])]
    if not faces:
        print(f'{path}: no embedded byte array to read')
        raise SystemExit(1)
    if len(faces) > 1:
        print(f'{path}: {len(faces)} embedded byte arrays, expected one face')
        raise SystemExit(1)
    face = faces[0]
    if '[_]u8{' in face['expr']:
        data = bytes(int(tok, 16) for tok in EMBED_BYTE.findall(face['expr']))
    else:
        parts = {m['name']: path.parent / m['path']
                 for m in IMPORT.finditer(text)}
        chunks = []
        for ref in PART_REF.finditer(face['expr']):
            name = ref['name']
            if name not in parts:
                print(f'{path}: face references {name}, which it does not import')
                raise SystemExit(1)
            chunks.append(read_embedded(parts[name]))
        data = b''.join(chunks)
    header = EMBED_COUNT.search(text[:face.start()])
    if header is not None:
        declared = int(header['count'].replace(',', ''))
        if len(data) != declared:
            print(f'{path}: initializer holds {len(data):,} bytes, '
                  f'header declares {declared:,}')
            raise SystemExit(1)
    return data


def at_base(value: float, upem: int) -> float:
    """A font-unit measurement in points at the 10pt base (em x 10)."""
    return value * 10.0 / upem


def num(value: float) -> str:
    """A measurement as Zig source: six decimals, trailing zeros dropped."""
    text = f'{value:.6f}'.rstrip('0').rstrip('.')
    return '0' if text in ('', '-0') else text


def style_rows(data: bytes) -> list[tuple[int, float, float, float]]:
    """`(cp, w, h, d)` rows for one embedded face, ascending by `cp`.

    `w` is the hmtx advance; `h`/`d` are the glyph's own ink bounds, so a
    blank glyph (space) contributes no ink at all. fontTools is imported
    here, keeping the plain `embed_font.py <font.otf>` path dependency-free.
    """
    try:
        from fontTools.pens.boundsPen import BoundsPen
        from fontTools.ttLib import TTFont
    except ImportError:
        print('fontTools is required for --style-metrics (pip install '
              'fonttools); the embed path itself does not need it')
        raise SystemExit(1) from None

    font = TTFont(io.BytesIO(data))
    upem = font['head'].unitsPerEm
    advances = font['hmtx'].metrics
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    rows = []
    for cp in range(*STYLE_CP_RANGE):
        name = cmap.get(cp)
        if name is None:
            continue
        pen = BoundsPen(glyphs)
        glyphs[name].draw(pen)
        bounds = pen.bounds or (0.0, 0.0, 0.0, 0.0)
        rows.append((
            cp,
            at_base(advances[name][0], upem),
            at_base(max(0.0, bounds[3]), upem),
            at_base(max(0.0, -bounds[1]), upem),
        ))
    return rows


def write_style_metrics() -> int:
    root = pathlib.Path(__file__).resolve().parent.parent
    tables = ''
    for name, source in STYLE_FACES:
        path = root / 'src' / 'fonts' / source
        if not path.is_file():
            print(f'no embedded face: {path}')
            return 1
        rows = style_rows(read_embedded(path))
        body = ''.join(
            f'\n    .{{ .cp = 0x{cp:04X}, .w = {num(w)}, .h = {num(h)}, '
            f'.d = {num(d)}, .ic = 0 }}, // U+{cp:04X}'
            for cp, w, h, d in rows
        )
        tables += STYLE_TABLE.format(
            name=name,
            label=source[len('lmroman_'):-len('.zig')].replace('_', ' '),
            count=len(rows),
            rows=body,
        )
    out = root / 'src' / 'layout' / 'roman_style_metrics.zig'
    out.write_text(STYLE_MODULE.format(tables=tables))
    print(f'{out.relative_to(root)}  ({len(STYLE_FACES)} tables)')
    return 0


# ── src/layout/ink_metrics.zig ───────────────────────────────────────────

# The five faces the renderer draws from, in the order `font.FontContext`
# declares them. `metrics.glyphInkAt` picks one by CharStyle with the same
# mapping `FontContext.faceForStyle` uses, so the outline a glyph is framed by
# is the outline it is drawn from.
INK_FACES = (
    ('math', 'lmmath.zig'),
    ('roman', 'lmroman_regular.zig'),
    ('italic', 'lmroman_italic.zig'),
    ('bold', 'lmroman_bold.zig'),
    ('bold_italic', 'lmroman_bold_italic.zig'),
)

# The `Edge` field names, in the order `ink_rows` yields them. A value of 0
# is left out of the emitted row: the Zig default is that same 0, so the
# generated table states the real measurement and stays inside 100 columns.
INK_FIELDS = ('asc', 'desc', 'left', 'right_edge', 'bottom')

INK_MODULE = '''//! Real ink of the five embedded faces, in em of the glyph's own font size,
//! generated by scripts/embed_font.py --ink-metrics from the bytes embedded
//! in src/fonts/ — the very bytes font.zig loads, so a glyph can never be
//! framed by one face's outline and drawn from another. Do not hand-edit;
//! re-run the generator.
//!
//! `asc`/`desc` are the glyph's REAL ink above and below its baseline — the
//! outline's own bounding box, rounded to six decimals — so a text box
//! bounds the ink that is actually painted instead of a rounded estimate of
//! it. `left` is how far the ink REACHES LEFT of the glyph origin, a
//! non-negative em (`-xMin`): a negative left side bearing, every combining
//! mark. `right_edge` is where the ink ENDS on the right, measured right
//! from the same origin (`max(0, xMax)`) — an ABSOLUTE edge, NOT an
//! overhang past the face's hmtx advance, so the consumer measures the
//! overhang against whatever advance it actually boxed the glyph by: a
//! static optical band (LMRoman17's `f`, 0.276em) is narrower than the
//! face's own advance (0.306em) while its ink runs to 0.357em, and only the
//! absolute edge frames that hook. `bottom` is the ink's lower edge measured
//! UP from the baseline, positive for a combining mark floating above its
//! base.
//!
//! A row exists for every codepoint the face's cmap maps to a painted glyph,
//! so the face's own ink answers wherever the face HAS a glyph. A codepoint
//! the face does not carry (an AMS-only symbol, a CJK glyph) has no row and
//! the consumer keeps its static fallback — a design bound for a fallback
//! face, not this face's ink.
//!
//! These rows are the BASE glyphs' outlines only. A MATH size VARIANT
//! (integral.v1 and the vertical/horizontal glyph constructions) is a
//! different, larger design measured from the MATH table, so no row here
//! claims that a variant shares its base's bbox.
//!
//! Rows are sorted by `cp` ascending — the binary-search invariant `lookup`
//! relies on.

/// One glyph's real ink, in em of the glyph's font size. A field the glyph
/// does not reach is omitted, and the 0 default IS that measurement: a row
/// states all five extents, never a placeholder.
pub const Edge = struct {{
    cp: u21,
    /// ink ABOVE the baseline, from the glyph's own outline
    asc: f32 = 0,
    /// ink BELOW the baseline, from the glyph's own outline
    desc: f32 = 0,
    /// ink reaching LEFT of the glyph origin (a negative left side bearing)
    left: f32 = 0,
    /// where the ink ENDS, measured RIGHT from the glyph origin — an
    /// absolute edge, not an overhang past the advance
    right_edge: f32 = 0,
    /// the ink's lower edge ABOVE the baseline; 0 when it sits on it or
    /// hangs below it (that descent is `desc`)
    bottom: f32 = 0,
}};

/// The row for `cp` in `table`, or null when it has none: binary search over
/// the `cp`-ascending rows, and the only reader of the tables below.
pub fn lookup(table: []const Edge, cp: u21) ?Edge {{
    var lo: usize = 0;
    var hi: usize = table.len;
    while (lo < hi) {{
        const mid = lo + (hi - lo) / 2;
        if (table[mid].cp < cp) lo = mid + 1 else hi = mid;
    }}
    if (lo >= table.len or table[lo].cp != cp) return null;
    return table[lo];
}}

{tables}'''

INK_TABLE = '''/// {label}, {count} rows.
pub const {name}: []const Edge = &.{{{rows}
}};

'''


def ink_rows(data: bytes) -> list[tuple[int, float, float, float, float, float]]:
    """`(cp, asc, desc, left, right_edge, bottom)` ink rows for one face.

    `asc`/`desc` are the glyph's own outline box above and below the
    baseline, in em — what the renderer actually paints, to six decimals
    instead of a rounded estimate. `left` is how far the ink reaches past
    the origin on the left, `max(0, -xMin)`, and `right_edge` is where it
    ENDS on the right, `max(0, xMax)` — an ABSOLUTE edge in em, so the
    consumer takes the overhang against the advance it boxed the glyph by
    (a static optical band can be narrower than this face's own hmtx
    advance, and an overhang recorded against the wider one would
    under-frame the ink it has to enclose). `bottom` is the ink's lower edge
    measured UP from the baseline in em, positive exactly for a mark that
    floats above its base. Every value is rounded to six decimals FIRST and
    a codepoint whose five values all round to zero gets no row at all: a
    glyph with no ink to frame (a blank, or ink a rounding step below the
    table's precision) is not a row. fontTools is imported here, keeping
    the plain `embed_font.py <font.otf>` path dependency-free.
    """
    try:
        from fontTools.pens.boundsPen import BoundsPen
        from fontTools.ttLib import TTFont
    except ImportError:
        print('fontTools is required for --ink-metrics (pip install '
              'fonttools); the embed path itself does not need it')
        raise SystemExit(1) from None

    font = TTFont(io.BytesIO(data))
    upem = font['head'].unitsPerEm
    glyphs = font.getGlyphSet()
    rows = []
    for cp, name in sorted(font.getBestCmap().items()):
        pen = BoundsPen(glyphs)
        glyphs[name].draw(pen)
        if pen.bounds is None:
            continue  # a blank glyph (space) paints nothing to frame
        x0, y0, x1, y1 = pen.bounds
        row = (
            cp,
            round(max(0.0, y1 / upem), 6),
            round(max(0.0, -y0 / upem), 6),
            round(max(0.0, -x0 / upem), 6),
            round(max(0.0, x1 / upem), 6),
            round(max(0.0, y0 / upem), 6),
        )
        if any(row[1:]):
            rows.append(row)
    return rows


def write_ink_metrics() -> int:
    root = pathlib.Path(__file__).resolve().parent.parent
    tables = ''
    for name, source in INK_FACES:
        path = root / 'src' / 'fonts' / source
        if not path.is_file():
            print(f'no embedded face: {path}')
            return 1
        rows = ink_rows(read_embedded(path))
        body = ''.join(
            # Trailing comma: an array-literal element needs one, and it also
            # keeps a hand-added row from silently joining the previous one.
            '\n    .{{ .cp = 0x{:04X}{} }},'.format(
                cp,
                ''.join(f', .{name} = {num(value)}'
                        for name, value in zip(INK_FIELDS, values) if value),
            )
            for cp, *values in rows
        )
        tables += INK_TABLE.format(
            name=name,
            label=source[:-len('.zig')].replace('lm', 'LM ', 1).replace('_', ' '),
            count=len(rows),
            rows=body,
        )
    out = root / 'src' / 'layout' / 'ink_metrics.zig'
    # One trailing newline: the blank line between tables is the separator,
    # but the file ends flush so `zig fmt` leaves the generated table alone.
    out.write_text(INK_MODULE.format(tables=tables).rstrip('\n') + '\n')
    print(f'{out.relative_to(root)}  ({len(INK_FACES)} tables)')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())