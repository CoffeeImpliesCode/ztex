# The five faces the renderer draws from, in the order `font.FontContext`
# declares them. `metrics.glyphInkAt` picks one by CharStyle with the same
# mapping `FontContext.faceForStyle` uses, so the outline a glyph is framed by
# is the outline it is drawn from.
INK_FACES = (
    ('math', 'lmmath.zig'),
    ('roman', 'lmroman_regular.zig'),
    ('italic', 'lmroman_italic.zig'),
    ('bold', 'lmroman_bold.zig'),
    ('bold_italic', 'lmroman_bold_italic.zig'),
)

# The `Edge` field names, in the order `ink_rows` yields them. A value of 0
# is left out of the emitted row: the Zig default is that same 0, so the
# generated table states the real measurement and stays inside 100 columns.
INK_FIELDS = ('asc', 'desc', 'left', 'right_edge', 'bottom')

INK_MODULE = '''//! Real ink of the five embedded faces, in em of the glyph's own font size,
//! generated by scripts/embed_font.py --ink-metrics from the bytes embedded
//! in src/fonts/ — the very bytes font.zig loads, so a glyph can never be
//! framed by one face's outline and drawn from another. Do not hand-edit;
//! re-run the generator.
//!
//! `asc`/`desc` are the glyph's REAL ink above and below its baseline — the
//! outline's own bounding box, rounded to six decimals — so a text box
//! bounds the ink that is actually painted instead of a rounded estimate of
//! it. `left` is how far the ink REACHES LEFT of the glyph origin, a
//! non-negative em (`-xMin`): a negative left side bearing, every combining
//! mark. `right_edge` is where the ink ENDS on the right, measured right
//! from the same origin (`max(0, xMax)`) — an ABSOLUTE edge, NOT an
//! overhang past the face's hmtx advance, so the consumer measures the
//! overhang against whatever advance it actually boxed the glyph by: a
//! static optical band (LMRoman17's `f`, 0.276em) is narrower than the
//! face's own advance (0.306em) while its ink runs to 0.357em, and only the
//! absolute edge frames that hook. `bottom` is the ink's lower edge measured
//! UP from the baseline, positive for a combining mark floating above its
//! base.
//!
//! A row exists for every codepoint the face's cmap maps to a painted glyph,
//! so the face's own ink answers wherever the face HAS a glyph. A codepoint
//! the face does not carry (an AMS-only symbol, a CJK glyph) has no row and
//! the consumer keeps its static fallback — a design bound for a fallback
//! face, not this face's ink.
//!
//! These rows are the BASE glyphs' outlines only. A MATH size VARIANT
//! (integral.v1 and the vertical/horizontal glyph constructions) is a
//! different, larger design measured from the MATH table, so no row here
//! claims that a variant shares its base's bbox.
//!
//! Rows are sorted by `cp` ascending — the binary-search invariant `lookup`
//! relies on.

/// One glyph's real ink, in em of the glyph's font size. A field the glyph
/// does not reach is omitted, and the 0 default IS that measurement: a row
/// states all five extents, never a placeholder.
pub const Edge = struct {{
    cp: u21,
    /// ink ABOVE the baseline, from the glyph's own outline
    asc: f32 = 0,
    /// ink BELOW the baseline, from the glyph's own outline
    desc: f32 = 0,
    /// ink reaching LEFT of the glyph origin (a negative left side bearing)
    left: f32 = 0,
    /// where the ink ENDS, measured RIGHT from the glyph origin — an
    /// absolute edge, not an overhang past the advance
    right_edge: f32 = 0,
    /// the ink's lower edge ABOVE the baseline; 0 when it sits on it or
    /// hangs below it (that descent is `desc`)
    bottom: f32 = 0,
}};

/// The row for `cp` in `table`, or null when it has none: binary search over
/// the `cp`-ascending rows, and the only reader of the tables below.
pub fn lookup(table: []const Edge, cp: u21) ?Edge {{
    var lo: usize = 0;
    var hi: usize = table.len;
    while (lo < hi) {{
        const mid = lo + (hi - lo) / 2;
        if (table[mid].cp < cp) lo = mid + 1 else hi = mid;
    }}
    if (lo >= table.len or table[lo].cp != cp) return null;
    return table[lo];
}}

{tables}'''

INK_TABLE = '''/// {label}, {count} rows.
pub const {name}: []const Edge = &.{{{rows}
}};

'''


def ink_rows(data: bytes) -> list[tuple[int, float, float, float, float, float]]:
    """`(cp, asc, desc, left, right_edge, bottom)` ink rows for one face.

    `asc`/`desc` are the glyph's own outline box above and below the
    baseline, in em — what the renderer actually paints, to six decimals
    instead of a rounded estimate. `left` is how far the ink reaches past
    the origin on the left, `max(0, -xMin)`, and `right_edge` is where it
    ENDS on the right, `max(0, xMax)` — an ABSOLUTE edge in em, so the
    consumer takes the overhang against the advance it boxed the glyph by
    (a static optical band can be narrower than this face's own hmtx
    advance, and an overhang recorded against the wider one would
    under-frame the ink it has to enclose). `bottom` is the ink's lower edge
    measured UP from the baseline in em, positive exactly for a mark that
    floats above its base. Every value is rounded to six decimals FIRST and
    a codepoint whose five values all round to zero gets no row at all: a
    glyph with no ink to frame (a blank, or ink a rounding step below the
    table's precision) is not a row. fontTools is imported here, keeping
    the plain `embed_font.py <font.otf>` path dependency-free.
    """
    try:
        from fontTools.pens.boundsPen import BoundsPen
        from fontTools.ttLib import TTFont
    except ImportError:
        print('fontTools is required for --ink-metrics (pip install '
              'fonttools); the embed path itself does not need it')
        raise SystemExit(1) from None

    font = TTFont(io.BytesIO(data))
    upem = font['head'].unitsPerEm
    glyphs = font.getGlyphSet()
    rows = []
    for cp, name in sorted(font.getBestCmap().items()):
        pen = BoundsPen(glyphs)
        glyphs[name].draw(pen)
        if pen.bounds is None:
            continue  # a blank glyph (space) paints nothing to frame
        x0, y0, x1, y1 = pen.bounds
        row = (
            cp,
            round(max(0.0, y1 / upem), 6),
            round(max(0.0, -y0 / upem), 6),
            round(max(0.0, -x0 / upem), 6),
            round(max(0.0, x1 / upem), 6),
            round(max(0.0, y0 / upem), 6),
        )
        if any(row[1:]):
            rows.append(row)
    return rows


def write_ink_metrics() -> int:
    root = pathlib.Path(__file__).resolve().parent.parent
    tables = ''
    for name, source in INK_FACES:
        path = root / 'src' / 'fonts' / source
        if not path.is_file():
            print(f'no embedded face: {path}')
            return 1
        rows = ink_rows(read_embedded(path))
        body = ''.join(
            # Trailing comma: an array-literal element needs one, and it also
            # keeps a hand-added row from silently joining the previous one.
            '\n    .{{ .cp = 0x{:04X}{} }},'.format(
                cp,
                ''.join(f', .{name} = {num(value)}'
                        for name, value in zip(INK_FIELDS, values) if value),
            )
            for cp, *values in rows
        )
        tables += INK_TABLE.format(
            name=name,
            label=source[:-len('.zig')].replace('lm', 'LM ', 1).replace('_', ' '),
            count=len(rows),
            rows=body,
        )
    out = root / 'src' / 'layout' / 'ink_metrics.zig'
    # One trailing newline: the blank line between tables is the separator,
    # but the file ends flush so `zig fmt` leaves the generated table alone.
    out.write_text(INK_MODULE.format(tables=tables).rstrip('\n') + '\n')
    print(f'{out.relative_to(root)}  ({len(INK_FACES)} tables)')
    return 0
